import fs from 'node:fs/promises';
import {Chess} from 'chess.js';
const meta=await fetch('https://api.github.com/repos/lichess-org/chess-openings/commits/master').then(r=>{if(!r.ok)throw Error(r.status);return r.json()});
const revision=meta.sha;
await fs.mkdir('vendor/openings',{recursive:true});
const rows=[];
for(const letter of ['a','b','c','d','e']) {
 const raw=await fetch(`https://raw.githubusercontent.com/lichess-org/chess-openings/${revision}/${letter}.tsv`).then(r=>r.text());
 for(const line of raw.trim().split('\n').slice(1)) {const [eco,name,pgn]=line.trim().split('\t');const c=new Chess();c.loadPgn(pgn);rows.push({eco,name,pgn,moves:c.history({verbose:true}).map(m=>m.from+m.to+(m.promotion||'')),position:c.fen().split(' ').slice(0,4).join(' ')});}
}
await fs.writeFile('src/openings.json',JSON.stringify(rows));
await fs.writeFile('vendor/openings/SOURCE.md',`Source: https://github.com/lichess-org/chess-openings\nRevision: ${revision}\nGenerated by scripts/update-openings.mjs from a..e.tsv using chess.js.\nLicence: CC0 1.0; see COPYING.txt.\n`);
await fs.writeFile('vendor/openings/COPYING.txt',await fetch(`https://raw.githubusercontent.com/lichess-org/chess-openings/${revision}/COPYING.txt`).then(r=>r.text()));
console.log(`${rows.length} openings, revision ${revision}`);
